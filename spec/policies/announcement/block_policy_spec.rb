# frozen_string_literal: true

require "rails_helper"

RSpec.describe Announcement::BlockPolicy, type: :policy do
  let(:event) { create(:event) }
  let(:system_user) { create(:user, email: User::SYSTEM_USER_EMAIL) }
  let(:author) { create(:user) }
  let(:announcement) { Announcement.create!(event:, author:, title: "Update", content: {}) }
  let(:block) { Announcement::Block::DonationSummary.create!(announcement:) }

  before { allow(User).to receive(:system_user).and_return(system_user) }

  describe "#edit? and #update?" do
    subject(:policy) { described_class.new(user, block) }

    context "as the manager who authored the announcement" do
      let(:user) { author }

      before { create(:organizer_position, user:, event:, role: :manager) }

      it "is allowed" do
        expect(policy.edit?).to eq(true)
        expect(policy.update?).to eq(true)
      end
    end

    context "as a manager who did not author the announcement" do
      let(:user) { create(:user) }

      before { create(:organizer_position, user:, event:, role: :manager) }

      it "is denied" do
        expect(policy.edit?).to eq(false)
        expect(policy.update?).to eq(false)
      end

      context "when the announcement was generated by HCB" do
        let(:author) { system_user }

        it "is allowed" do
          expect(policy.edit?).to eq(true)
          expect(policy.update?).to eq(true)
        end
      end
    end

    context "as a member when the announcement was generated by HCB" do
      let(:author) { system_user }
      let(:user) { create(:user) }

      before { create(:organizer_position, user:, event:, role: :member) }

      it "is denied" do
        expect(policy.edit?).to eq(false)
        expect(policy.update?).to eq(false)
      end
    end

    context "as an admin" do
      let(:user) { create(:user, :make_admin) }

      it "is allowed" do
        expect(policy.edit?).to eq(true)
        expect(policy.update?).to eq(true)
      end
    end
  end
end
